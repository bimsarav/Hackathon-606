#!/usr/bin/env bash
# Generates a service's demo-seed migration from the legacy data.
#   tools/seed/export.sh <service>      e.g. directory-service
# Runs tools/seed/queries/<service>.sql (SELECT statements that emit SQL text, one statement per row) against the
# legacy DB and writes services/<service>/src/main/resources/db/seed/V900__demo_seed.sql.
# The seed is applied only with Spring profile `demo` (spring.flyway.locations includes classpath:db/seed).
set -euo pipefail
cd "$(dirname "$0")"
SVC="${1:?service name}"
Q="queries/$SVC.sql"
OUT="../../services/$SVC/src/main/resources/db/seed/V900__demo_seed.sql"
[ -f "$Q" ] || { echo "missing $Q" >&2; exit 1; }
./legacy-db.sh up >/dev/null
mkdir -p "$(dirname "$OUT")"
{
  echo "-- GENERATED by tools/seed/export.sh $SVC from the supplied ESMP dump (synthetic data). Do not edit by hand."
  echo "-- Demo profile only. Legacy IDs are preserved; identity sequences are advanced at the end."
  ./legacy-db.sh psql -q -At -v ON_ERROR_STOP=1 < "$Q"
} > "$OUT"
echo "wrote $OUT ($(grep -c '' "$OUT") lines)"
