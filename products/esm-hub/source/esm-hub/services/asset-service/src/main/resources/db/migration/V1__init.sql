-- asset-service schema. Tenant boundary: company_id. Users and offices are referenced by id only (directory replica).
CREATE TABLE assets (
  asset_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT       NOT NULL,
  asset_tag        VARCHAR(30)  NOT NULL,
  asset_type       VARCHAR(40)  NOT NULL,
  manufacturer     VARCHAR(60),
  model            VARCHAR(80),
  serial_number    VARCHAR(80),
  purchase_date    DATE,
  warranty_end     DATE,
  office_id        BIGINT,
  assigned_user_id BIGINT,
  asset_status     VARCHAR(20)  NOT NULL CHECK (asset_status IN ('IN_STOCK','ASSIGNED','REPAIR','RETIRED','LOST')),
  purchase_cost    NUMERIC(12,2) CHECK (purchase_cost IS NULL OR purchase_cost >= 0),
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_asset_tag UNIQUE (company_id, asset_tag),
  CONSTRAINT ck_asset_assignment CHECK ((asset_status = 'ASSIGNED') = (assigned_user_id IS NOT NULL)),
  CONSTRAINT ck_asset_warranty CHECK (warranty_end IS NULL OR purchase_date IS NULL OR warranty_end >= purchase_date)
);
CREATE UNIQUE INDEX ux_asset_serial ON assets (company_id, serial_number) WHERE serial_number IS NOT NULL;
CREATE INDEX idx_assets_company_status ON assets (company_id, asset_status);
CREATE INDEX idx_assets_assignee ON assets (assigned_user_id);

CREATE TABLE asset_assignments (
  assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id      BIGINT      NOT NULL REFERENCES assets ON DELETE CASCADE,
  user_id       BIGINT      NOT NULL,
  assigned_at   TIMESTAMPTZ NOT NULL,
  returned_at   TIMESTAMPTZ,
  assigned_by   BIGINT,
  CHECK (returned_at IS NULL OR returned_at >= assigned_at)
);
CREATE UNIQUE INDEX ux_asset_current_assignment ON asset_assignments (asset_id) WHERE returned_at IS NULL;
