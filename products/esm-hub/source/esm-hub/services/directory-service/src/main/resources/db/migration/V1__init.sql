-- directory-service schema (organisation, identity, service master data). Tenant boundary: company_id.
CREATE TABLE companies (
  company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  code       VARCHAR(20)  NOT NULL UNIQUE
);
CREATE TABLE offices (
  office_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT       NOT NULL REFERENCES companies,
  name       VARCHAR(100) NOT NULL,
  city       VARCHAR(80)  NOT NULL,
  country    VARCHAR(80)  NOT NULL,
  timezone   VARCHAR(60)  NOT NULL
);
CREATE TABLE departments (
  department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT       NOT NULL REFERENCES companies,
  name          VARCHAR(100) NOT NULL,
  cost_centre   VARCHAR(30)
);
CREATE TABLE roles (
  role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name   VARCHAR(60) NOT NULL UNIQUE,
  description TEXT
);
CREATE TABLE users (
  user_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT       NOT NULL REFERENCES companies,
  employee_no       VARCHAR(20)  NOT NULL UNIQUE,
  first_name        VARCHAR(60)  NOT NULL,
  last_name         VARCHAR(60)  NOT NULL,
  email             VARCHAR(160) NOT NULL,
  office_id         BIGINT REFERENCES offices,
  department_id     BIGINT REFERENCES departments,
  manager_id        BIGINT REFERENCES users,
  employment_status VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (employment_status IN ('ACTIVE','INACTIVE','ON_LEAVE')),
  password_hash     VARCHAR(100),
  failed_logins     INTEGER      NOT NULL DEFAULT 0,
  locked_until      TIMESTAMPTZ,
  last_login_at     TIMESTAMPTZ,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CHECK (manager_id IS NULL OR manager_id <> user_id)
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE INDEX idx_users_company ON users (company_id);
CREATE TABLE user_roles (
  user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles,
  PRIMARY KEY (user_id, role_id)
);
CREATE TABLE teams (
  team_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT       NOT NULL REFERENCES companies,
  name            VARCHAR(100) NOT NULL,
  support_level   INTEGER      NOT NULL CHECK (support_level BETWEEN 1 AND 3),
  manager_user_id BIGINT REFERENCES users,
  is_active       BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE TABLE team_members (
  team_id   BIGINT NOT NULL REFERENCES teams ON DELETE CASCADE,
  user_id   BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
  joined_at DATE   NOT NULL DEFAULT CURRENT_DATE,
  PRIMARY KEY (team_id, user_id)
);
CREATE TABLE service_categories (
  category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80) NOT NULL UNIQUE,
  parent_id   BIGINT REFERENCES service_categories
);
CREATE TABLE services (
  service_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT       NOT NULL REFERENCES companies,
  category_id    BIGINT REFERENCES service_categories,
  name           VARCHAR(120) NOT NULL,
  description    TEXT,
  owning_team_id BIGINT REFERENCES teams,
  is_active      BOOLEAN      NOT NULL DEFAULT TRUE
);

