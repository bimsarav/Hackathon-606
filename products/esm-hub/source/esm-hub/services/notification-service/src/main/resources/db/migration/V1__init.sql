-- notification-service: one row per (event, recipient, channel). IN_APP rows are shown in the inbox,
-- EMAIL rows are claimed by the sender (FOR UPDATE SKIP LOCKED) and retried with exponential backoff.
CREATE TABLE notifications (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT       NOT NULL,
  user_id         BIGINT       NOT NULL,
  channel         VARCHAR(20)  NOT NULL CHECK (channel IN ('IN_APP', 'EMAIL')),
  subject         VARCHAR(200) NOT NULL,
  body            TEXT         NOT NULL,
  link            VARCHAR(200),
  reference       VARCHAR(60),
  entity_type     VARCHAR(50),
  entity_id       VARCHAR(60),
  delivery_status VARCHAR(20)  NOT NULL CHECK (delivery_status IN ('PENDING', 'DELIVERED', 'SENT', 'FAILED', 'DEAD')),
  attempts        INTEGER      NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_error      VARCHAR(500),
  event_id        UUID,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  sent_at         TIMESTAMPTZ,
  read_at         TIMESTAMPTZ,
  CONSTRAINT uq_notification_dedupe UNIQUE (event_id, user_id, channel)
);
CREATE INDEX idx_notifications_inbox ON notifications (user_id, channel, notification_id DESC);
CREATE INDEX idx_notifications_due ON notifications (next_attempt_at) WHERE channel = 'EMAIL' AND delivery_status IN ('PENDING', 'FAILED');
CREATE INDEX idx_notifications_company_status ON notifications (company_id, delivery_status);
