-- knowledge-service schema. Tenant boundary: company_id. Users are referenced by id only (directory replica).
CREATE TABLE articles (
  article_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT       NOT NULL,
  title             VARCHAR(200) NOT NULL,
  body              TEXT         NOT NULL,
  category_id       BIGINT,
  author_id         BIGINT,
  reviewed_by       BIGINT,
  status            VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT','UNDER_REVIEW','PUBLISHED','RETIRED')),
  view_count        INTEGER      NOT NULL DEFAULT 0,
  helpful_count     INTEGER      NOT NULL DEFAULT 0,
  not_helpful_count INTEGER      NOT NULL DEFAULT 0,
  published_at      TIMESTAMPTZ,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_articles_company_status ON articles (company_id, status);
CREATE INDEX idx_articles_fts ON articles USING GIN (to_tsvector('english', title || ' ' || body));

CREATE TABLE article_feedback (
  article_id BIGINT      NOT NULL REFERENCES articles ON DELETE CASCADE,
  user_id    BIGINT      NOT NULL,
  helpful    BOOLEAN     NOT NULL,
  comment    VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (article_id, user_id)
);
