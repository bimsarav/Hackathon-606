-- change-service schema. Tenant boundary: company_id. Directory data (users, teams) is read from the replica.
CREATE TABLE changes (
  change_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_no     VARCHAR(20)  NOT NULL UNIQUE,
  company_id    BIGINT       NOT NULL,
  title         VARCHAR(200) NOT NULL,
  description   TEXT         NOT NULL,
  change_type   VARCHAR(20)  NOT NULL CHECK (change_type IN ('STANDARD','NORMAL','EMERGENCY')),
  status        VARCHAR(25)  NOT NULL CHECK (status IN ('DRAFT','ASSESSMENT','APPROVAL','SCHEDULED','IMPLEMENTING','IMPLEMENTED','FAILED','CLOSED','REJECTED','CANCELLED')),
  risk_level    VARCHAR(15)  CHECK (risk_level IN ('LOW','MEDIUM','HIGH')),
  impact        VARCHAR(15)  CHECK (impact IN ('LOW','MEDIUM','HIGH')),
  requester_id  BIGINT       NOT NULL,
  owner_team_id BIGINT,
  planned_start TIMESTAMPTZ,
  planned_end   TIMESTAMPTZ,
  actual_start  TIMESTAMPTZ,
  actual_end    TIMESTAMPTZ,
  rollback_plan TEXT,
  created_at    TIMESTAMPTZ  NOT NULL,
  updated_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_changes_company_status ON changes (company_id, status);
CREATE INDEX idx_changes_requester ON changes (requester_id);
CREATE INDEX idx_changes_team ON changes (owner_team_id);
CREATE INDEX idx_changes_window ON changes (planned_start, planned_end);

CREATE TABLE change_approvals (
  approval_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_id     BIGINT       NOT NULL REFERENCES changes ON DELETE CASCADE,
  step_order    INTEGER      NOT NULL,
  approver_id   BIGINT,
  approver_role VARCHAR(60),
  decision      VARCHAR(10)  NOT NULL CHECK (decision IN ('PENDING','APPROVED','REJECTED')),
  comments      TEXT,
  created_at    TIMESTAMPTZ  NOT NULL,
  decided_at    TIMESTAMPTZ,
  decided_by    BIGINT,
  CHECK (approver_id IS NOT NULL OR approver_role IS NOT NULL)
);
CREATE INDEX idx_change_approvals_change ON change_approvals (change_id);
CREATE INDEX idx_change_approvals_pending ON change_approvals (decision, approver_role);
