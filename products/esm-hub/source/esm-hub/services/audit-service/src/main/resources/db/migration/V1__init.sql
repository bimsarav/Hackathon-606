-- audit-service schema: append-only audit store. Tenant boundary: company_id. Users are referenced by id only.
CREATE TABLE audit_records (
  audit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id       UUID UNIQUE,                -- Kafka envelope id (NULL for seeded legacy rows); makes ingestion idempotent
  company_id     BIGINT,
  service        VARCHAR(60)  NOT NULL,
  actor_user_id  BIGINT,
  entity_type    VARCHAR(50)  NOT NULL,
  entity_id      VARCHAR(64)  NOT NULL,
  action         VARCHAR(40)  NOT NULL,
  old_values     JSONB,
  new_values     JSONB,
  source_ip      VARCHAR(45),
  correlation_id VARCHAR(64),
  occurred_at    TIMESTAMPTZ  NOT NULL,
  recorded_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_company_time ON audit_records (company_id, occurred_at DESC, audit_id DESC);
CREATE INDEX idx_audit_entity ON audit_records (company_id, entity_type, entity_id);
CREATE INDEX idx_audit_actor ON audit_records (company_id, actor_user_id);

CREATE FUNCTION audit_records_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit_records is append-only (% blocked)', TG_OP USING ERRCODE = 'restrict_violation';
END;
$$;
CREATE TRIGGER trg_audit_no_update_delete BEFORE UPDATE OR DELETE ON audit_records
  FOR EACH ROW EXECUTE FUNCTION audit_records_immutable();
CREATE TRIGGER trg_audit_no_truncate BEFORE TRUNCATE ON audit_records
  FOR EACH STATEMENT EXECUTE FUNCTION audit_records_immutable();
