-- incident-service schema (database esm_incident). Directory data (users, teams, services, offices) lives in the
-- dir_* replica tables (classpath:db/directory); IDs that point there are plain BIGINTs without FKs (ADR-0004).

-- ---------- Reference data: priorities, statuses, workflow ----------
CREATE TABLE priorities (
  priority_id        INTEGER PRIMARY KEY,
  name               VARCHAR(20) NOT NULL UNIQUE,
  response_minutes   INTEGER     NOT NULL CHECK (response_minutes > 0),
  resolution_minutes INTEGER     NOT NULL,
  CHECK (resolution_minutes >= response_minutes)
);

CREATE TABLE ticket_statuses (
  status_id  INTEGER PRIMARY KEY,
  name       VARCHAR(30) NOT NULL UNIQUE,
  is_closed  BOOLEAN     NOT NULL DEFAULT FALSE,
  pauses_sla BOOLEAN     NOT NULL DEFAULT FALSE      -- BQ-2: SLA clock pauses while in this status
);

CREATE TABLE status_transitions (
  from_status_id INTEGER NOT NULL REFERENCES ticket_statuses,
  to_status_id   INTEGER NOT NULL REFERENCES ticket_statuses,
  PRIMARY KEY (from_status_id, to_status_id),
  CHECK (from_status_id <> to_status_id)
);

-- ---------- SLA: versioned policies, calendars, escalation ----------
CREATE TABLE sla_policies (
  sla_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id                BIGINT,                 -- NULL = install-wide default
  name                      VARCHAR(100) NOT NULL,
  priority_id               INTEGER      NOT NULL REFERENCES priorities,
  service_id                BIGINT,                 -- NULL = all services
  business_hours_only       BOOLEAN      NOT NULL DEFAULT TRUE,
  response_target_minutes   INTEGER      NOT NULL,
  resolution_target_minutes INTEGER      NOT NULL,
  effective_from            DATE         NOT NULL,
  effective_to              DATE,
  version                   INTEGER      NOT NULL DEFAULT 1,
  CONSTRAINT ck_sla_targets CHECK (response_target_minutes > 0 AND resolution_target_minutes >= response_target_minutes),
  CONSTRAINT ck_sla_dates CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX idx_sla_policies_lookup ON sla_policies (priority_id, company_id, service_id);

CREATE TABLE business_calendars (
  calendar_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80) NOT NULL UNIQUE,
  timezone    VARCHAR(60) NOT NULL
);

CREATE TABLE calendar_hours (
  calendar_id BIGINT  NOT NULL REFERENCES business_calendars ON DELETE CASCADE,
  weekday     INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),   -- 0 = Monday
  start_time  TIME    NOT NULL,
  end_time    TIME    NOT NULL,
  PRIMARY KEY (calendar_id, weekday),
  CHECK (end_time > start_time)
);

CREATE TABLE calendar_holidays (
  calendar_id  BIGINT       NOT NULL REFERENCES business_calendars ON DELETE CASCADE,
  holiday_date DATE         NOT NULL,
  name         VARCHAR(100) NOT NULL,
  PRIMARY KEY (calendar_id, holiday_date)
);

-- Office timezone (from the directory replica) -> business calendar
CREATE TABLE timezone_calendars (
  timezone    VARCHAR(60) PRIMARY KEY,
  calendar_id BIGINT NOT NULL REFERENCES business_calendars ON DELETE CASCADE
);

CREATE TABLE escalation_rules (
  rule_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT,                           -- NULL = install-wide default
  priority_id     INTEGER REFERENCES priorities,    -- NULL = every priority
  trigger_type    VARCHAR(30) NOT NULL CHECK (trigger_type IN ('RESPONSE_BREACH','RESOLUTION_AT_RISK','RESOLUTION_BREACH')),
  notify_role     VARCHAR(60) NOT NULL,             -- TEAM_LEAD = lead of the assigned team; otherwise a platform role
  notify_assignee BOOLEAN     NOT NULL DEFAULT TRUE,
  active          BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE assignment_rules (
  rule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT  NOT NULL,
  service_id  BIGINT,
  priority_id INTEGER REFERENCES priorities,
  team_id     BIGINT  NOT NULL,
  sort_order  INTEGER NOT NULL DEFAULT 100,
  active      BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_assignment_rules_company ON assignment_rules (company_id, sort_order);

-- ---------- Incidents ----------
CREATE TABLE incidents (
  incident_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          BIGINT       NOT NULL,
  ticket_no           VARCHAR(20)  NOT NULL UNIQUE,
  title               VARCHAR(200) NOT NULL,
  description         TEXT         NOT NULL,
  requester_id        BIGINT       NOT NULL,
  service_id          BIGINT,
  asset_id            BIGINT,
  priority_id         INTEGER      NOT NULL REFERENCES priorities,
  status_id           INTEGER      NOT NULL REFERENCES ticket_statuses,
  assigned_team_id    BIGINT,
  assigned_user_id    BIGINT,
  sla_id              BIGINT REFERENCES sla_policies,
  channel             VARCHAR(20)  NOT NULL CHECK (channel IN ('PORTAL','EMAIL','PHONE','CHAT','MONITORING')),
  created_at          TIMESTAMPTZ  NOT NULL,
  updated_at          TIMESTAMPTZ  NOT NULL,
  first_response_at   TIMESTAMPTZ,
  resolved_at         TIMESTAMPTZ,
  closed_at           TIMESTAMPTZ,
  response_due_at     TIMESTAMPTZ,
  due_at              TIMESTAMPTZ,
  sla_paused_since    TIMESTAMPTZ,
  sla_paused_minutes  INTEGER      NOT NULL DEFAULT 0,
  response_breached   BOOLEAN      NOT NULL DEFAULT FALSE,
  resolution_breached BOOLEAN      NOT NULL DEFAULT FALSE,
  resolution_code     VARCHAR(40),
  resolution_notes    TEXT,
  satisfaction_score  INTEGER CHECK (satisfaction_score BETWEEN 1 AND 5),
  reopened_count      INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_incidents_company_status ON incidents (company_id, status_id);
CREATE INDEX idx_incidents_assignee ON incidents (assigned_user_id);
CREATE INDEX idx_incidents_team ON incidents (assigned_team_id);
CREATE INDEX idx_incidents_requester ON incidents (requester_id);

CREATE TABLE incident_comments (
  comment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT      NOT NULL REFERENCES incidents ON DELETE CASCADE,
  author_id   BIGINT      NOT NULL,
  body        TEXT        NOT NULL,
  is_internal BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_comments_incident ON incident_comments (incident_id);

CREATE TABLE worklogs (
  worklog_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id      BIGINT      NOT NULL REFERENCES incidents ON DELETE CASCADE,
  user_id          BIGINT      NOT NULL,
  minutes_spent    INTEGER     NOT NULL CHECK (minutes_spent > 0),
  work_description TEXT        NOT NULL,
  logged_at        TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_worklogs_incident ON worklogs (incident_id);

-- Timeline (status changes, assignment, SLA pause/resume, reopen, escalation)
CREATE TABLE incident_events (
  event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT      NOT NULL REFERENCES incidents ON DELETE CASCADE,
  event_type  VARCHAR(30) NOT NULL,
  from_value  VARCHAR(100),
  to_value    VARCHAR(100),
  actor_id    BIGINT,
  occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_incident_events ON incident_events (incident_id, occurred_at);

-- One escalation per incident and trigger (deduplicates the SLA scan across runs and replicas)
CREATE TABLE incident_escalations (
  incident_id  BIGINT      NOT NULL REFERENCES incidents ON DELETE CASCADE,
  trigger_type VARCHAR(30) NOT NULL,
  escalated_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (incident_id, trigger_type)
);

-- NFR-11: Idempotency-Key on create
CREATE TABLE idempotency_keys (
  user_id     BIGINT       NOT NULL,
  idem_key    VARCHAR(100) NOT NULL,
  endpoint    VARCHAR(100) NOT NULL,
  resource_id BIGINT       NOT NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, idem_key, endpoint)
);

-- ---------- Problems (FR-7) ----------
CREATE TABLE problems (
  problem_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT       NOT NULL,
  problem_no    VARCHAR(20)  NOT NULL UNIQUE,
  title         VARCHAR(200) NOT NULL,
  description   TEXT,
  status        VARCHAR(25)  NOT NULL CHECK (status IN ('OPEN','INVESTIGATING','KNOWN_ERROR','RESOLVED','CLOSED')),
  root_cause    TEXT,
  workaround    TEXT,
  known_error   BOOLEAN      NOT NULL DEFAULT FALSE,
  owner_team_id BIGINT,
  created_at    TIMESTAMPTZ  NOT NULL,
  updated_at    TIMESTAMPTZ  NOT NULL,
  resolved_at   TIMESTAMPTZ
);
CREATE INDEX idx_problems_company ON problems (company_id, status);

CREATE TABLE incident_problem_links (
  incident_id BIGINT NOT NULL REFERENCES incidents ON DELETE CASCADE,
  problem_id  BIGINT NOT NULL REFERENCES problems ON DELETE CASCADE,
  PRIMARY KEY (incident_id, problem_id)
);
CREATE INDEX idx_problem_links_problem ON incident_problem_links (problem_id);
