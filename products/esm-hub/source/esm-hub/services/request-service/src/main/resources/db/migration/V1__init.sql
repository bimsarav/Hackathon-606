-- request-service schema. Tenant boundary: company_id. Directory data (users, teams, services) is read from the replica.
CREATE TABLE catalogue_items (
  item_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT        NOT NULL,
  service_id         BIGINT        NOT NULL,
  name               VARCHAR(150)  NOT NULL,
  description        TEXT,
  base_cost          NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (base_cost >= 0),
  fulfilment_team_id BIGINT,
  active             BOOLEAN       NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_items_company ON catalogue_items (company_id);

CREATE TABLE approval_steps (
  item_id       BIGINT        NOT NULL REFERENCES catalogue_items ON DELETE CASCADE,
  step_order    INTEGER       NOT NULL CHECK (step_order BETWEEN 1 AND 10),
  approver_type VARCHAR(10)   NOT NULL CHECK (approver_type IN ('MANAGER','ROLE')),
  approver_role VARCHAR(60),
  min_cost      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (min_cost >= 0),
  CHECK (approver_type = 'MANAGER' OR approver_role IS NOT NULL)
);
CREATE INDEX idx_steps_item ON approval_steps (item_id);

CREATE TABLE service_requests (
  request_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_no       VARCHAR(20)   NOT NULL UNIQUE,
  company_id       BIGINT        NOT NULL,
  requester_id     BIGINT        NOT NULL,
  service_id       BIGINT,
  item_id          BIGINT REFERENCES catalogue_items,
  title            VARCHAR(200)  NOT NULL,
  details          TEXT,
  status           VARCHAR(25)   NOT NULL CHECK (status IN ('SUBMITTED','PENDING_APPROVAL','APPROVED','REJECTED','IN_PROGRESS','FULFILLED','CANCELLED')),
  estimated_cost   NUMERIC(12,2),
  assigned_team_id BIGINT,
  assigned_user_id BIGINT,
  requested_at     TIMESTAMPTZ   NOT NULL,
  updated_at       TIMESTAMPTZ   NOT NULL,
  approved_at      TIMESTAMPTZ,
  fulfilled_at     TIMESTAMPTZ
);
CREATE INDEX idx_requests_company_status ON service_requests (company_id, status);
CREATE INDEX idx_requests_requester ON service_requests (requester_id);
CREATE INDEX idx_requests_team ON service_requests (assigned_team_id);

CREATE TABLE request_approvals (
  approval_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id    BIGINT       NOT NULL REFERENCES service_requests ON DELETE CASCADE,
  step_order    INTEGER      NOT NULL,
  approver_id   BIGINT,
  approver_role VARCHAR(60),
  decision      VARCHAR(10)  NOT NULL CHECK (decision IN ('PENDING','APPROVED','REJECTED')),
  comments      TEXT,
  created_at    TIMESTAMPTZ  NOT NULL,
  decided_at    TIMESTAMPTZ,
  decided_by    BIGINT,
  CHECK (approver_id IS NOT NULL OR approver_role IS NOT NULL)
);
CREATE INDEX idx_approvals_request ON request_approvals (request_id);
CREATE INDEX idx_approvals_pending ON request_approvals (decision, approver_id);

CREATE TABLE idempotency_keys (
  user_id    BIGINT       NOT NULL,
  idem_key   VARCHAR(100) NOT NULL,
  scope      VARCHAR(60)  NOT NULL,
  entity_id  BIGINT       NOT NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, idem_key, scope)
);
